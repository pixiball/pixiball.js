async function readSource(url: string): Promise<string> {
	if (url.startsWith('file:')) return readFile(fileURLToPath(url), 'utf8')

	const response = await fetch(url)
	if (!response.ok) {
		throw new Error(
			`Failed to fetch the headless source: ${response.status} ${response.statusText}`,
		)
	}

	return response.text()
}

export async function updateHeadless(): Promise<HeadlessSourceMetadata> {
	const source = await readSource(SOURCE_URL)
	if (!source) throw new Error('The PixiBall headless source is empty')

	const metadata = inspectHeadlessSource(source)
	const output = createGeneratedModule(metadata, source)
	const temporaryPath = `${OUTPUT_PATH}.tmp`

	await mkdir(dirname(OUTPUT_PATH), { recursive: true })
	await writeFile(temporaryPath, output, 'utf8')
	await rename(temporaryPath, OUTPUT_PATH)

	if (process.env.GITHUB_OUTPUT) {
		await appendFile(
			process.env.GITHUB_OUTPUT,
			`new_hash=${metadata.sourceHash}\n`,
			'utf8',
		)
	}

	console.log(`SUCCESS:${metadata.sourceHash}`)
	return metadata
}

if (import.meta.main) await updateHeadless()
