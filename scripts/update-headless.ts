import { createHash } from 'node:crypto'
import {
	appendFile,
	mkdir,
	readFile,
	rename,
	writeFile,
} from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE_URL =
	process.env.PIXIBALL_HEADLESS_URL ??
	'https://www.pixiball.com/headless-min.js'
const OUTPUT_PATH = resolve('src/generated/headless.ts')

export interface HeadlessSourceMetadata {
	version: string
	gameVersion: string
	sourceHash: string
}

function countMatches(source: string, pattern: RegExp): number {
	return [...source.matchAll(pattern)].length
}

export function inspectHeadlessSource(source: string): HeadlessSourceMetadata {
	const banner = source.match(
		/^\/\*\s*\n\s*PixiBall headless host\s*\n\s*version (\S+)\s*\n\s*game (\S+)\s*\n\*\//,
	)

	if (!banner?.[1] || !banner[2]) {
		throw new Error('The headless source is missing its PixiBall header')
	}

	const invariants: Array<[string, RegExp, number]> = [
		['HBInit assignment', /window\.HBInit\s*=/g, 1],
		['WebSocket construction', /new WebSocket\(/g, 1],
		['room link element', /getElementById\("roomlink"\)/g, 1],
		['captcha element', /getElementById\("recaptcha"\)/g, 1],
		['error element', /getElementById\("error"\)/g, 1],
	]

	for (const [name, pattern, expected] of invariants) {
		const actual = countMatches(source, pattern)
		if (actual !== expected) {
			throw new Error(
				`Expected ${expected} ${name} occurrence, found ${actual}`,
			)
		}
	}

	return {
		version: banner[1],
		gameVersion: banner[2],
		sourceHash: createHash('sha256').update(source).digest('hex').slice(0, 8),
	}
}

